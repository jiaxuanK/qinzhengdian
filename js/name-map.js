/* ============================================================
   name-map.js · 妃嫔【编号 → 名字】映射表  ★ 你要改名字就改这里 ★
   ------------------------------------------------------------
   用法极其简单：左边是 assets/images 里的文件夹名，右边是游戏里显示的名字。
   想给某位妃子改名，改右边引号里的字，然后重新生成清单即可（见手册）。

       '01': '碧痕',     ← 把「碧痕」改成你想要的名字

   规则：
   1) 左边必须是【文件夹名】，右边是【显示名】。
   2) 右边不要填位分（才人 / 美人 / 婕妤 / 嫔 / 妃 / 贵妃）——
      位分是册封系统自动给的，名字撞位分会显示成「位分：婕妤，名字：婕妤」。
   3) 右边不要和别的妃子重名，也不要和位分重名。
   4) 【没写进表里的编号也能用】！例如你新建文件夹 17、18，
      程序会自动从 js/asset-names.js 的雅名池里挑一个稳定名字给她们，
      同一个编号永远是同一个名字，不会每次刷新乱变。
      只有你想【指定】名字时，才需要往这张表里加一行。
   5) 中文名的文件夹（朝云 / 洛神 / 钰 …）不需要登记，直接用文件夹名当名字。

   为什么用数字编号当文件夹名：
   - 存档是靠文件夹名认人的（rareKey），编号永不重复、永不需要改；
   - 名字单独放这张表，改名字不影响存档、不影响图片路径、不掉档；
   - 排序整齐，以后加人只要顺延 17、18、19…

   ★ 重要：本表只改「显示名」，绝不改磁盘文件夹名、图片路径和存档键。
   ============================================================ */
